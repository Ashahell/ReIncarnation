/* Sign-correct round-half-away of p/32767. */
static int32_t qround(int32_t p) {
    if (p >= 0)
        return (p + 16383) / 32767;
    return -((-p + 16383) / 32767);
}

static void put(unsigned char *rgba, int x, int y, uint32_t c) {
    unsigned char *p = rgba + ((uint32_t)y * 64u + (uint32_t)x) * 4u;
    p[0] = (unsigned char)((c >> 16) & 0xffu);
    p[1] = (unsigned char)((c >> 8) & 0xffu);
    p[2] = (unsigned char)(c & 0xffu);
    p[3] = 255;
}

void ri_knob_render_frame(unsigned char *rgba, int value) {
    int deg, x, y;
    int32_t sx, cx;
    int r, w;
    if (!rgba)
        return;
    if (value < 0)
        value = 0;
    if (value > 127)
        value = 127;
    deg = ri_knob_pointer_mdeg(value) / 1000;
    deg = (deg + 360) % 360;
    sx = RI_SIN_Q15[deg];
    cx = RI_SIN_Q15[(deg + 90) % 360];
    for (y = 0; y < 64; y++) {
        for (x = 0; x < 64; x++) {
            int32_t dx = 2 * x - 62;
            int32_t dy = 2 * y - 62;
            int32_t d2 = dx * dx + dy * dy;
            int base, add;
            unsigned char *p = rgba + ((uint32_t)y * 64u + (uint32_t)x) * 4u;
            if (d2 > 2704) {
                p[0] = p[1] = p[2] = p[3] = 0;
                continue;
            }
            base = 69 + (28 - 69) * y / 63;
            if (d2 > 2401) {
                put(rgba, x, y, RI_KNOB_RIM);
            } else if (d2 > 1849 && dy < 0 && 4 * dy * dy > d2) {
                add = base + 45;
                if (add > 255)
                    add = 255;
                p[0] = p[1] = p[2] = (unsigned char)add;
                p[3] = 255;
            } else {
                if (dx < 0 && dy < 0) {
                    add = (1400 * (2704 - d2) / 2704) / 100;
                    base += add;
                    if (base > 255)
                        base = 255;
                }
                p[0] = p[1] = p[2] = (unsigned char)base;
                p[3] = 255;
            }
        }
    }
    /* Pointer: r 6..22, 3 px wide, over everything but the hub. */
    for (r = 6; r <= 22; r++) {
        for (w = -1; w <= 1; w++) {
            int32_t px = -cx, py = sx;
            int32_t X = 32 + qround((int32_t)r * sx + (int32_t)w * px);
            int32_t Y = 32 - qround((int32_t)r * cx + (int32_t)w * py);
            if (X < 0 || X > 63 || Y < 0 || Y > 63)
                continue;
            {
                int32_t dx = 2 * (int)X - 62, dy = 2 * (int)Y - 62;
                int32_t d2 = dx * dx + dy * dy;
                if (d2 > 100)
                    put(rgba, (int)X, (int)Y, RI_KNOB_POINTER);
            }
        }
    }
    /* Hub + hub ring (over the pointer tail). */
    for (y = 0; y < 64; y++) {
        for (x = 0; x < 64; x++) {
            int32_t dx = 2 * x - 62, dy = 2 * y - 62;
            int32_t d2 = dx * dx + dy * dy;
            if (d2 <= 100)
                put(rgba, x, y, RI_KNOB_HUB);
            else if (d2 <= 144)
                put(rgba, x, y, RI_KNOB_HUB_RIM);
        }
    }
}
